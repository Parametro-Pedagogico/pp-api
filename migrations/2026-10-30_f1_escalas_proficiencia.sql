-- F1 (escalas de proficiência — opção A) — config de escala por avaliação.
-- O motor devolve θ (logito); o central converte para a escala de reporte e classifica o nível,
-- por configuração. Ver pp-app/docs/contrato-escalas.md. Idempotente.

BEGIN;

CREATE TABLE IF NOT EXISTS scale (
  id          text PRIMARY KEY,             -- ex.: 'saeb-0-500'
  nome        text NOT NULL,
  niveis      jsonb NOT NULL DEFAULT '[]',  -- [{codigo, rotulo, cor}], ordem crescente (AB..AV)
  referencias jsonb NOT NULL DEFAULT '[]',  -- [{fonte, componente, etapa, valor}]
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS scale_component (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scale_id    text NOT NULL REFERENCES scale(id) ON DELETE CASCADE,
  componente  text NOT NULL,                -- LP/MT/CH/CN
  etapa       smallint NOT NULL,            -- ano/série (2/5/9...)
  a           double precision NOT NULL,    -- transform P = a*θ + b
  b           double precision NOT NULL,
  cortes      jsonb NOT NULL DEFAULT '[]',  -- limiares crescentes na escala P (len = níveis-1)
  UNIQUE (scale_id, componente, etapa)
);

-- A avaliação (edição) aponta para a escala usada.
ALTER TABLE macro_assessments ADD COLUMN IF NOT EXISTS scale_id text REFERENCES scale(id);

INSERT INTO pp_schema_migrations (filename)
SELECT '2026-10-30_f1_escalas_proficiencia.sql'
WHERE NOT EXISTS (
  SELECT 1 FROM pp_schema_migrations WHERE filename = '2026-10-30_f1_escalas_proficiencia.sql'
);

COMMIT;
